#!/usr/bin/env bash
# Regenerate shared/abis/*.ts from the local forge build artifacts.
# (`forge inspect abi` pretty-prints a table in current forge — artifacts
# are the stable machine-readable source. TS output (not JSON) so viem
# gets full literal-type inference with zero import friction.)
# Run from the REPO ROOT:  bun run abis
# (Ticket 04 — frontend/indexer always consume live types, zero copying.)
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT/contracts"

forge build
mkdir -p "$ROOT/shared/src/abis"
bun -e '
import { readFileSync, writeFileSync } from "node:fs";
const contracts = [
  "AttesterRegistry",
  "AttestationRegistry",
  "ConsentRegistry",
  "ChallengeModule",
  "MockLendingPool",
];
for (const c of contracts) {
  const artifact = JSON.parse(readFileSync(`out/${c}.sol/${c}.json`, "utf8"));
  const name = c.charAt(0).toLowerCase() + c.slice(1) + "Abi";
  const header = "// GENERATED by `bun run abis` (contracts/script/export-abis.sh). DO NOT EDIT.\n";
  writeFileSync(`../shared/src/abis/${c}.ts`, `${header}export const ${name} = ${JSON.stringify(artifact.abi)} as const;\n`);
}
console.log("exported 5 ABIs to shared/src/abis/");
'
